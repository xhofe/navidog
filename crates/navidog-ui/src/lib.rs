/// Localized text for a `navidog.*` error code. Server diagnostics do not
/// match and stay untouched.
pub fn app_error_text(code: &str) -> Option<String> {
    let key = match code {
        "navidog.session_closed" => "ui.app_session_closed",
        "navidog.not_relational" => "ui.app_not_relational",
        "navidog.no_result" => "ui.app_no_result",
        "navidog.unsupported_kind" => "ui.app_unsupported_kind",
        "navidog.timeout" => "ui.app_timeout",
        "navidog.read_timeout" => "ui.app_read_timeout",
        "navidog.bad_params" => "ui.app_bad_params",
        "navidog.ssh_auth" => "ui.app_ssh_auth",
        "navidog.no_database_file" => "ui.app_no_database_file",
        "navidog.database_missing" => "ui.app_database_missing",
        "navidog.row_not_found" => "ui.app_row_not_found",
        _ => return None,
    };
    Some(t!(key).to_string())
}

/// User-facing text for a driver error. The database message stays as the server sent it;
/// a dead session adds a localized note about reopening.
pub fn db_error_text(
    code: Option<&str>,
    message: &str,
    disconnected: bool,
    outcome_unknown: bool,
) -> String {
    db_error_text_with(
        code,
        message,
        disconnected,
        outcome_unknown,
        |detail| format!("{detail} {}", t!("ui.session_lost")),
        |detail| format!("{detail} {}", t!("ui.outcome_unknown")),
    )
}

/// Formats the original driver diagnostic and delegates recovery copy to its UI surface.
/// Unknown execution outcomes take precedence over session loss. A healthy-session error
/// returns the diagnostic unchanged and does not invoke either recovery formatter.
pub fn db_error_text_with(
    code: Option<&str>,
    message: &str,
    disconnected: bool,
    outcome_unknown: bool,
    session_lost_text: impl FnOnce(&str) -> String,
    outcome_unknown_text: impl FnOnce(&str) -> String,
) -> String {
    let detail = match code {
        // Errors generated by navidog itself carry a stable code. Prefer the
        // localized sentence over the English diagnostic; unknown codes keep
        // the server/driver text verbatim.
        Some("navidog.database_missing") => {
            let text = app_error_text("navidog.database_missing")
                .unwrap_or_else(|| "The database file does not exist.".to_string());
            format!("{text} {message}")
        }
        Some(code) => app_error_text(code).unwrap_or_else(|| format!("{code} - {message}")),
        None => message.to_string(),
    };
    if outcome_unknown {
        outcome_unknown_text(&detail)
    } else if disconnected {
        session_lost_text(&detail)
    } else {
        detail
    }
}

#[cfg(test)]
mod tests {
    use super::{app_error_text, db_error_text_with};

    #[test]
    fn app_error_codes_are_localized_but_server_codes_are_not() {
        let previous = rust_i18n::locale().to_string();
        rust_i18n::set_locale("zh-CN");
        assert_eq!(
            app_error_text("navidog.session_closed").as_deref(),
            Some("数据库会话已关闭。")
        );
        rust_i18n::set_locale("en");
        assert_eq!(
            app_error_text("navidog.session_closed").as_deref(),
            Some("The database session is closed.")
        );
        assert!(app_error_text("08006").is_none());
        rust_i18n::set_locale(&previous);
    }

    #[test]
    fn database_recovery_selects_one_formatter_and_preserves_the_diagnostic() {
        let message = "original driver diagnostic\n数据库诊断";
        for code in [None, Some("08006")] {
            let expected = match code {
                Some(code) => format!("{code} - {message}"),
                None => message.to_string(),
            };
            assert_eq!(
                db_error_text_with(
                    code,
                    message,
                    false,
                    false,
                    |_| panic!("a plain diagnostic needs no recovery text"),
                    |_| panic!("a plain diagnostic needs no recovery text"),
                ),
                expected,
            );
            assert_eq!(
                db_error_text_with(
                    code,
                    message,
                    true,
                    false,
                    |detail| format!("session lost: {detail}"),
                    |_| panic!("a known outcome must not use unknown-outcome text"),
                ),
                format!("session lost: {expected}"),
            );
            for disconnected in [false, true] {
                assert_eq!(
                    db_error_text_with(
                        code,
                        message,
                        disconnected,
                        true,
                        |_| panic!("unknown outcomes take precedence over session loss"),
                        |detail| format!("outcome unknown: {detail}"),
                    ),
                    format!("outcome unknown: {expected}"),
                );
            }
        }
    }
    #[test]
    fn a_missing_sqlite_file_keeps_its_path() {
        let previous = rust_i18n::locale().to_string();
        rust_i18n::set_locale("en");
        let text = db_error_text_with(
            Some("navidog.database_missing"),
            "/tmp/navidog-missing.db",
            false,
            false,
            |_| unreachable!(),
            |_| unreachable!(),
        );
        assert!(text.contains("/tmp/navidog-missing.db"), "{text}");
        rust_i18n::set_locale(&previous);
    }
}
